CREATE TABLE user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    lastname VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_user_accounts_email UNIQUE (email)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role VARCHAR(255) NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role),
    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id) REFERENCES user_accounts (id) ON DELETE CASCADE
);

CREATE TABLE payrolls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    period_month INTEGER NOT NULL,
    period_year INTEGER NOT NULL,
    salary BIGINT NOT NULL,
    CONSTRAINT fk_payrolls_employee
        FOREIGN KEY (employee_id) REFERENCES user_accounts (id),
    CONSTRAINT uk_payroll_employee_period
        UNIQUE (employee_id, period_month, period_year),
    CONSTRAINT ck_payroll_month
        CHECK (period_month BETWEEN 1 AND 12),
    CONSTRAINT ck_payroll_salary
        CHECK (salary >= 0)
);

CREATE TABLE security_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_date DATE NOT NULL,
    action VARCHAR(255) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    event_object VARCHAR(255) NOT NULL,
    path VARCHAR(255) NOT NULL
);

CREATE INDEX idx_security_events_date ON security_events (event_date);
CREATE INDEX idx_security_events_action ON security_events (action);
